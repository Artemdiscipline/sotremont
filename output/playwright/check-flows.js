async (page) => {
  const results = [];
  const check = (condition, label) => { if (!condition) throw new Error(label); results.push(label); };
  await page.goto('http://127.0.0.1:5173/');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Открыть меню', exact: true }).click();
  check(await page.getByRole('navigation', { name: 'Основная навигация' }).isVisible(), 'Мобильное меню открывается');
  await page.keyboard.press('Escape');
  check(await page.getByRole('button', { name: 'Открыть меню', exact: true }).getAttribute('aria-expanded') === 'false', 'Escape закрывает меню');
  await page.getByRole('link', { name: 'Узнать стоимость', exact: true }).click();
  await page.getByRole('combobox', { name: 'Модель если знаете', exact: true }).fill('iPhone 14');
  await page.getByRole('radio', { name: 'Разбит экран', exact: true }).check();
  await page.getByRole('button', { name: 'Подсказать ремонт', exact: true }).click();
  check(await page.locator('.diagnostic-result h3').textContent() === 'Замена дисплея', 'Экран → возможная замена дисплея');
  const message = await page.getByLabel('Ваша заявка мастеру', { exact: true }).inputValue();
  check(message.includes('iPhone 14') && message.includes('Разбит экран'), 'Заявка содержит выбранную модель и симптом');
  const whatsapp = await page.getByRole('link', { name: 'Отправить в WhatsApp' }).getAttribute('href');
  check(decodeURIComponent(whatsapp.split('?text=')[1]) === message && whatsapp.startsWith('https://wa.me/79959421338?'), 'WhatsApp содержит точный закодированный текст и верный номер');
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write']);
  await page.getByRole('button', { name: 'Скопировать текст заявки', exact: true }).click();
  check(await page.evaluate(() => navigator.clipboard.readText().then(text => text.replace(/\r\n/g, '\n'))) === message, 'Текст заявки реально копируется в Clipboard');
  await page.context().route('https://t.me/**', route => route.fulfill({ status: 200, contentType: 'text/html', body: '<title>Telegram test destination</title>' }));
  const popupPromise = page.waitForEvent('popup');
  await page.getByRole('button', { name: 'Скопировать заявку и открыть Telegram', exact: true }).click();
  const popup = await popupPromise;
  await popup.waitForURL('https://t.me/sotremont');
  check(popup.url() === 'https://t.me/sotremont', 'После копирования открывается правильный Telegram');
  await popup.close();
  await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async () => { throw new Error('Denied for QA'); } } }));
  await page.getByRole('button', { name: 'Скопировать заявку и открыть Telegram', exact: true }).click();
  await page.getByRole('link', { name: 'Открыть Telegram', exact: true }).waitFor();
  check((await page.getByRole('status').innerText()).includes('вручную'), 'Отказ Clipboard показывает ручной fallback');
  check(await page.getByRole('link', { name: 'Открыть Telegram', exact: true }).getAttribute('href') === 'https://t.me/sotremont', 'Ручной переход Telegram доступен после ошибки');
  await page.getByRole('button', { name: 'Уточнить цену: Замена заднего стекла', exact: true }).click();
  await page.getByRole('button', { name: 'Подсказать ремонт', exact: true }).click();
  check(await page.locator('.diagnostic-result h3').textContent() === 'Замена заднего стекла', 'Карточка заднего стекла сохраняет выбранную услугу');
  check((await page.getByLabel('Ваша заявка мастеру', { exact: true }).inputValue()).includes('Разбито заднее стекло'), 'Заднее стекло правильно попадает в заявку');
  await page.getByRole('button', { name: 'Уточнить цену: Диагностика устройства', exact: true }).click();
  check(await page.getByRole('radio', { name: 'Другая проблема', exact: true }).isChecked(), 'Общая диагностика не подставляет попадание воды');
  await page.getByLabel('Расскажите подробнее', { exact: true }).fill('Старые подробности');
  await page.getByRole('radio', { name: 'Нет звука', exact: true }).check();
  await page.getByRole('button', { name: 'Подсказать ремонт', exact: true }).click();
  check(!(await page.getByLabel('Ваша заявка мастеру', { exact: true }).inputValue()).includes('Старые подробности'), 'Скрытое описание не попадает в новую заявку');
  await page.getByRole('radio', { name: 'Планшет', exact: true }).check();
  await page.getByRole('combobox', { name: 'Модель если знаете', exact: true }).fill('iPad Air');
  await page.getByRole('button', { name: 'Подсказать ремонт', exact: true }).click();
  check((await page.getByLabel('Ваша заявка мастеру', { exact: true }).inputValue()).includes('Планшет'), 'Категория устройства обновляет заявку');
  await page.getByRole('button', { name: 'Политика конфиденциальности', exact: true }).click();
  check(await page.getByRole('dialog').isVisible(), 'Политика открывается в доступном диалоге');
  await page.keyboard.press('Escape');
  check(!await page.getByRole('dialog').isVisible(), 'Escape закрывает политику');
  const slider = page.getByRole('slider');
  await slider.focus();
  await page.keyboard.press('ArrowRight');
  check(await slider.inputValue() === '51', 'Сравнение до/после доступно с клавиатуры');
  const brokenAnchors = await page.evaluate(() => [...document.querySelectorAll('a[href^="#"]')].map(a => a.getAttribute('href')).filter(href => href !== '#' && !document.getElementById(href.slice(1))));
  check(brokenAnchors.length === 0, 'Все внутренние якоря существуют');
  const phoneLinks = await page.locator('a[href^="tel:"]').evaluateAll(links => links.map(a => a.getAttribute('href')));
  check(phoneLinks.every(link => link === 'tel:+79959421338'), 'Все телефонные ссылки правильные');
  const accessoryLinks = await page.locator('.accessory-card').evaluateAll(links => links.map(a => a.getAttribute('href')));
  check(accessoryLinks.length === 6 && accessoryLinks.every(link => decodeURIComponent(link.split('?text=')[1]).includes('наличие')), 'Все 6 категорий аксессуаров формируют реальные запросы наличия');
  check(await page.evaluate(() => getComputedStyle(document.documentElement).scrollBehavior) === 'auto', 'prefers-reduced-motion отключает плавную прокрутку');
  return results;
}


